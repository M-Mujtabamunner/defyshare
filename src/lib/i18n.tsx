export const LANGUAGES = [
  { code: 'en', label: 'English', dict: en as Dict, rtl: false },
  { code: 'ur', label: 'اردو', dict: ur, rtl: true },
  { code: 'hi', label: 'हिन्दी', dict: hi, rtl: false },
  { code: 'ar', label: 'العربية', dict: ar, rtl: true },
  { code: 'es', label: 'Español', dict: es, rtl: false },
  { code: 'fr', label: 'Français', dict: fr, rtl: false },
] as const;

export type LangCode = (typeof LANGUAGES)[number]['code'];

const LANG_KEY = 'defyshare:lang';

const detect = (): LangCode => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && LANGUAGES.some((l) => l.code === saved)) return saved as LangCode;
  } catch {
    /* ignore */
  }
  const nav = (navigator.languages ?? [navigator.language]).map((l) => l.slice(0, 2).toLowerCase());
  return (nav.find((l) => LANGUAGES.some((x) => x.code === l)) as LangCode) ?? 'en';
};

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

interface I18nContextType {
  lang: LangCode;
  setLang: (lang: LangCode) => void;
  t: Translate;
}

const format = (s: string, vars?: Record<string, string | number>) =>
  vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : s;

const I18nContext = createContext<I18nContextType>({ lang: 'en', setLang: () => undefined, t: (k, v) => format(en[k], v) });

export const I18nProvider = ({ children }: { children: React.ReactNode }) => {
  const [lang, setLangState] = useState<LangCode>(detect);
  const meta = LANGUAGES.find((l) => l.code === lang) ?? LANGUAGES[0];

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = meta.rtl ? 'rtl' : 'ltr';
  }, [lang, meta.rtl]);

  const setLang = useCallback((next: LangCode) => {
    setLangState(next);
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback<Translate>((key, vars) => format(meta.dict[key] ?? en[key], vars), [meta]);

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
};

export const useT = () => useContext(I18nContext);
